//! The behavioural cases, as data a browser can drive — `NOCTUA.md §9.3` Leg 3.
//!
//! Two outputs from one source, which is the whole point:
//!
//! | Output | Read by |
//! |---|---|
//! | `dist/component-cases.json` | the runner, `tests/conformance/cases.spec.js` |
//! | `docs-site/src/generated/cases.rs` | the documentation binary, which renders each case's Dioxus half |
//!
//! # Why a case becomes a tree
//!
//! Because an example already is one (`docs-site/src/tree.rs`), and a tree is
//! the shape both implementations can draw: the Rust side walks it through the
//! generated components, and `example-react.js` walks the same data through the
//! React ones. A case is an example nobody reads — same props, same two
//! renderings, no prose around it — so it costs one emitter rather than a
//! second mounting path that would have to be kept in step with the first.

use std::fmt::Write as _;

use noctua_design_spec::component::{Component, Kind};
use noctua_design_spec::conformance::{Cases, PropValue};

use crate::{COMPONENT_SPEC, CommentStyle, EmittedFile, header_from};

/// Emits the case data and the trees that draw it.
#[must_use]
pub fn emit(cases: &[(String, Cases)], components: &[Component]) -> Vec<EmittedFile> {
    vec![
        EmittedFile::new("dist/component-cases.json", json(cases)),
        EmittedFile::new("docs-site/src/generated/cases.rs", trees(cases, components)),
        EmittedFile::new("docs-site/js/conformance-enhance.js", enhancers()),
    ]
}

/// The id a case is known by, in the markup and in the JSON.
///
/// Derived rather than declared: two names for one case is one of them going
/// stale, and the runner has to find in the DOM what the JSON told it about.
#[must_use]
pub fn id(component: &str, index: usize) -> String {
    format!(
        "case-{}-{index}",
        noctua_design_spec::component::file_stem(component).replace('_', "-")
    )
}

fn json(cases: &[(String, Cases)]) -> String {
    // The header a generated file owes, in the one shape JSON has for it —
    // `dist/lineage.cases.json` set the precedent, and a reader who opens
    // either has to be told where it came from and how to make it again.
    let mut out = format!(
        "{{\n  \"_generated\": \"Generated by noctua-design — do not edit. Source: \
         {COMPONENT_SPEC}. Regenerate: cargo xtask build.\",\n  \"case\": [\n"
    );
    let mut first = true;
    for (component, set) in cases {
        for (index, case) in set.case.iter().enumerate() {
            if !first {
                out.push_str(",\n");
            }
            first = false;
            let _ = write!(
                out,
                "  {{\"component\": {component:?}, \"id\": {:?}, \"name\": {:?}, \"steps\": [{}], \
                 \"expect\": {{{}}}}}",
                id(component, index),
                case.name,
                case.steps
                    .iter()
                    .map(|step| format!("{step:?}"))
                    .collect::<Vec<_>>()
                    .join(", "),
                expectation(case)
            );
        }
    }
    out.push_str("\n  ]\n}\n");
    out
}

/// One case's expectation, as the runner reads it.
fn expectation(case: &noctua_design_spec::conformance::Case) -> String {
    let mut parts = Vec::new();
    if !case.expect.focus.is_empty() {
        parts.push(format!("\"focus\": {:?}", case.expect.focus));
    }
    if !case.expect.attrs.is_empty() {
        let pairs = case
            .expect
            .attrs
            .iter()
            .map(|(name, value)| format!("{name:?}: {value:?}"))
            .collect::<Vec<_>>()
            .join(", ");
        parts.push(format!("\"attrs\": {{{pairs}}}"));
    }
    if !case.expect.absent.is_empty() {
        parts.push(format!(
            "\"absent\": [{}]",
            case.expect
                .absent
                .iter()
                .map(|name| format!("{name:?}"))
                .collect::<Vec<_>>()
                .join(", ")
        ));
    }
    for (key, list) in [
        ("visible", &case.expect.visible),
        ("present", &case.expect.present),
        ("hidden", &case.expect.hidden),
    ] {
        if !list.is_empty() {
            parts.push(format!(
                "\"{key}\": [{}]",
                list.iter()
                    .map(|one| format!("{one:?}"))
                    .collect::<Vec<_>>()
                    .join(", ")
            ));
        }
    }
    if let Some(value) = &case.expect.value {
        parts.push(format!("\"value\": {value:?}"));
    }
    if !case.expect.text.is_empty() {
        parts.push(format!("\"text\": {:?}", case.expect.text));
    }
    parts.join(", ")
}

fn trees(cases: &[(String, Cases)], components: &[Component]) -> String {
    let mut out = header_from(CommentStyle::Line("//!"), COMPONENT_SPEC);
    out.push_str(
        "\n//! Every behavioural case, as a tree the interpreter can draw.\n\
         //!\n\
         //! `NOCTUA.md §9.3` Leg 3. The runner drives these in a browser, in both\n\
         //! implementations, against `dist/component-cases.json`.\n\n\
         use crate::tree::{Node, Value};\n\n\
         /// `(component, id, tree)`, in the order the contracts declare them.\n\
         pub(crate) const CASES: &[(&str, &str, &[Node])] = &[\n",
    );
    for (component, set) in cases {
        let declared = components
            .iter()
            .find(|one| one.meta.name == *component)
            .expect("the loader only yields cases for components it read");
        for (index, case) in set.case.iter().enumerate() {
            let props = case
                .props
                .iter()
                .map(|(name, value)| {
                    let kind = declared.prop.get(name).map(|prop| prop.kind);
                    format!("({name:?}, {})", literal(value, kind))
                })
                .collect::<Vec<_>>()
                .join(", ");
            let mut children = if case.children.is_empty() {
                String::new()
            } else {
                format!("Node::Text(Value::Data({:?}))", case.children)
            };
            for child in &case.child {
                if !children.is_empty() {
                    children.push_str(", ");
                }
                children.push_str(&nested(child, components));
            }
            let _ = writeln!(
                out,
                "    ({component:?}, {:?}, &[Node::Component {{ name: {component:?}, \
                 props: &[{props}], children: &[{children}] }}]),",
                id(component, index)
            );
        }
    }
    out.push_str("];\n");
    out
}

/// One child of a case, and whatever is inside it.
fn nested(child: &noctua_design_spec::conformance::Child, components: &[Component]) -> String {
    let declared = components
        .iter()
        .find(|one| one.meta.name == child.component);
    let props = child
        .props
        .iter()
        .map(|(name, value)| {
            let kind = declared
                .and_then(|one| one.prop.get(name))
                .map(|prop| prop.kind);
            format!("({name:?}, {})", literal(value, kind))
        })
        .collect::<Vec<_>>()
        .join(", ");
    let mut inside = if child.text.is_empty() {
        String::new()
    } else {
        format!("Node::Text(Value::Data({:?}))", child.text)
    };
    for deeper in &child.child {
        if !inside.is_empty() {
            inside.push_str(", ");
        }
        inside.push_str(&nested(deeper, components));
    }
    format!(
        "Node::Component {{ name: {:?}, props: &[{props}], children: &[{inside}] }}",
        child.component
    )
}

/// A case's value, in the tree language.
///
/// The prop's own kind decides: an enum or a bool is an identifier the same in
/// every locale, and a `text` prop is content a reader sees — which is
/// `Value::Data`, the variant that says *literal, and deliberately not a
/// sentence to translate*.
fn literal(value: &PropValue, kind: Option<Kind>) -> String {
    match value {
        PropValue::Boolean(yes) => format!("Value::Bool({yes})"),
        PropValue::Integer(number) => format!("Value::Text({:?})", number.to_string()),
        other => {
            let text = other.as_str().unwrap_or_default();
            if matches!(kind, Some(Kind::Text)) {
                format!("Value::Data({text:?})")
            } else {
                format!("Value::Text({text:?})")
            }
        }
    }
}

/// Every shipped behaviour, behind one `enhance` and one `release`.
///
/// **Apparatus, and it lives outside `dist/` for that reason.** `NOCTUA.md
/// §9.5` refuses an aggregate that undoes tree-shaking for a consumer, and this
/// is one — a page that imports it pays for every module. The conformance page
/// is the only page that wants exactly that: it mounts one of everything, so it
/// needs one of every behaviour, and a hand-written list here would be a list
/// that goes stale the day a module is added.
///
/// The names are read out of the modules themselves rather than derived from
/// their file names: `select.js` exports `enhanceSelects`, `tabs.js` exports
/// `enhanceTabs`, and no rule turns one into the other.
fn enhancers() -> String {
    let mut imports = String::new();
    let mut enhance = String::new();
    let mut release = String::new();
    for (path, text) in noctua_design_runtime::sources() {
        let file = path.rsplit('/').next().unwrap_or(path);
        let names: Vec<&str> = text
            .lines()
            .filter_map(|line| line.strip_prefix("export function "))
            .filter_map(|rest| rest.split('(').next())
            .filter(|name| name.starts_with("enhance") || name.starts_with("release"))
            .collect();
        if names.is_empty() {
            continue;
        }
        let _ = writeln!(
            imports,
            "import {{ {} }} from \"../assets/{file}\";",
            names.join(", ")
        );
        for name in names {
            let call = format!("  {name}(root);\n");
            if name.starts_with("enhance") {
                enhance.push_str(&call);
            } else {
                release.push_str(&call);
            }
        }
    }
    format!(
        "{}\n{imports}\n/// Everything this system ships, turned on.\nexport function enhance(root = document) {{\n{enhance}}}\n\n\
         /// And off again.\nexport function release(root = document) {{\n{release}}}\n",
        header_from(CommentStyle::Line("//"), crate::SPEC)
    )
}
