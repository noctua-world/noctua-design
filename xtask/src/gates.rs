//! Source gates.
//!
//! A convention nothing enforces is a convention that decays. Each gate below
//! corresponds to an invariant in `AGENTS.md`, and each exists because the
//! failure it prevents is **silent**: a hardcoded color looks fine until the
//! palette changes, a raw `13px` looks fine until the scale moves, a named font
//! family looks fine until someone turns on the interface-font setting.
//!
//! # The escape hatch
//!
//! Every gate honours `allow-literal: <reason>` on the same line, in whatever
//! comment syntax the file uses. The reason is mandatory and is not checked for
//! content — its job is to put the exception in front of a reviewer, not to be
//! parsed.
//!
//! **A marker on its own line does not work**, and that is deliberate. `rustfmt`
//! is free to move a comment that sits above a statement, which would silently
//! separate a marker from the literal it excuses and fail a file that was
//! passing. `noctua-colors` lost time to exactly that. Same line, or no
//! exemption.

use std::path::{Path, PathBuf};

/// One thing a gate objected to.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct Finding {
    /// Repository-relative path, forward slashes.
    pub(crate) file: String,
    /// 1-indexed.
    pub(crate) line: usize,
    /// What is wrong, and why it matters.
    pub(crate) message: String,
}

/// The marker that excuses a line from every gate.
pub(crate) const ALLOW: &str = "allow-literal:";

/// Directories a gate never walks, each for a stated reason.
///
/// **These gates are about component and styling source.** That is what the
/// invariants in `AGENTS.md` say, and it is the only place they mean anything:
/// a component that hardcodes `13px` is a component that will sit between two
/// steps forever, while a *compiler* that formats `0.25rem` into CSS must
/// contain the string `0.25rem` — it is the thing producing the token.
///
/// Excluding a directory here is therefore a claim, and the claim is tested:
/// [`tests::the_gates_cover_component_source`] asserts that the places a
/// component can live are still walked.
const SKIP: [&str; 12] = [
    ".git",
    "target",
    "node_modules",
    // Build output and generated source. Verified against the spec by the
    // drift check, which is a stronger guarantee than a lint over the text —
    // and which legitimately contains whatever the spec says.
    "dist",
    "crates/noctua-design-tokens/src",
    "crates/noctua-design-icons/src",
    // The pre-rendered site. Every byte of it came from a source file the
    // gates already walked, so a finding here would be a finding reported
    // twice and fixable in neither place.
    "docs-site/dist",
    // The bundled React examples. Somebody else's minified React with an
    // interpreter inside it, reproduced by one command and committed nowhere —
    // the same standing as `dist/vendor`, and gated for the same reason:
    // reviewing a `1em` inside a minified bundle is not a thing anybody does.
    "docs-site/assets/react",
    // The vendored `noctua-colors` output. It is *made* of color literals,
    // which is the entire point of it, and it is generated by another
    // repository — nothing here may edit it, so a finding would be unfixable.
    "packages/tokens",
    // The compiler itself. It carries the token defaults (`0.25rem`), the
    // values it formats (`48rem`), the family names it writes into a font
    // stack, and diagnostics quoting all three. Marking each one individually
    // would be twenty lines of ceremony that trains people to reach for the
    // escape hatch.
    "crates/noctua-design-spec",
    "crates/noctua-design-emit",
    "xtask",
];

/// Where a component or a stylesheet can live.
///
/// The gates' reason for existing. Kept beside [`SKIP`] so the two are read
/// together, and asserted by a test: an exclusion list is only safe while
/// somebody checks it did not swallow the thing being protected.
#[cfg(test)]
const COVERED: [&str; 5] = [
    "crates/noctua-design/src",
    "packages/react/src",
    // The component rules ship, so they answer to the colour, token and
    // arbitrary-value gates exactly as they did when they were part of the
    // site's own stylesheet. `dist/` is skipped, and this is where they live.
    "crates/noctua-design-styles/src",
    "docs-site",
    "assets",
];

/// Runs every gate over the repository's own source.
///
/// # Errors
///
/// Only a filesystem failure. A gate *finding* is a returned value, not an
/// error, so one pass reports everything rather than stopping at the first.
pub(crate) fn run(
    root: &Path,
    spec: &noctua_design_spec::Spec,
    vendor: &noctua_design_spec::Vendor,
) -> Result<Vec<Finding>, String> {
    // Read from the spec rather than restated: the breakpoint gate below asks
    // whether a media query names a DECLARED width, and a second list here
    // would answer that question against itself.
    let breakpoints: Vec<String> = spec.breakpoint.values().cloned().collect();

    // Every custom property anything declares. Collected before anything is
    // inspected, because `var(--noctua-space-40)` — a token that does not
    // exist — is not a syntax error: the declaration is simply dropped and the
    // element falls back to whatever it would have been. A grid silently
    // becomes one column. Nothing reports it, in the browser or here, and this
    // repository shipped exactly that while writing a gate for something else.
    let mut declared = std::collections::BTreeSet::new();
    let paths = sources(root)?;
    for path in &paths {
        if let Ok(text) = std::fs::read_to_string(path) {
            collect_declarations(&text, &mut declared);
        }
    }
    // The generated stylesheets are where the token layer actually lives.
    for name in [
        "tokens.css",
        "theme.css",
        "fonts.css",
        "scope.css",
        "tones.css",
    ] {
        if let Ok(text) = std::fs::read_to_string(root.join("dist").join(name)) {
            collect_declarations(&text, &mut declared);
        }
    }
    // AND THE COLOR NAMES, WHICH THIS GATE USED TO WAVE THROUGH.
    //
    // `--nc-*` was exempt outright, on the grounds that those names come from
    // the vendored output — which is true and is not the same as saying they
    // all exist. `--nc-color-danger-text` does not: there is `--nc-color-danger`,
    // `-bg`, `-border` and `-hover`, and the fourth spelling was dropped at
    // computed-value time with no error, leaving an error sentence the same
    // colour as the paragraph above it. `Vendor::declared` was written for
    // exactly this and nothing had ever passed it in.
    declared.extend(vendor.declared.iter().cloned());

    let mut findings = Vec::new();
    for path in paths {
        let relative = path
            .strip_prefix(root)
            .unwrap_or(&path)
            .to_string_lossy()
            .replace('\\', "/");
        let text = std::fs::read_to_string(&path)
            .map_err(|error| format!("could not read {relative}: {error}"))?;
        inspect(&relative, &text, &breakpoints, &declared, &mut findings);
    }
    findings.sort_by(|a, b| (&a.file, a.line).cmp(&(&b.file, b.line)));
    Ok(findings)
}

/// Every `--name:` a stylesheet declares.
fn collect_declarations(text: &str, into: &mut std::collections::BTreeSet<String>) {
    for line in text.lines() {
        let mut rest = line;
        while let Some(at) = rest.find("--") {
            rest = &rest[at..];
            let name: String = rest
                .chars()
                .take_while(|c| c.is_ascii_alphanumeric() || *c == '-' || *c == '_')
                .collect();
            rest = &rest[name.len()..];
            // A declaration, not a use: `--x: value`, with nothing but spaces
            // between the name and the colon.
            if rest.trim_start().starts_with(':') && !name.is_empty() {
                into.insert(name);
            }
        }
    }
}

/// Every file a gate applies to, in a stable order.
fn sources(root: &Path) -> Result<Vec<PathBuf>, String> {
    const EXTENSIONS: [&str; 7] = ["rs", "css", "scss", "ts", "tsx", "js", "jsx"];
    let mut found = Vec::new();
    walk(root, root, &EXTENSIONS, &mut found)?;
    found.sort();
    Ok(found)
}

fn walk(
    root: &Path,
    directory: &Path,
    extensions: &[&str],
    into: &mut Vec<PathBuf>,
) -> Result<(), String> {
    let entries = std::fs::read_dir(directory)
        .map_err(|error| format!("could not read {}: {error}", directory.display()))?;

    let mut paths: Vec<PathBuf> = Vec::new();
    for entry in entries {
        paths.push(
            entry
                .map_err(|error| format!("could not read an entry: {error}"))?
                .path(),
        );
    }
    paths.sort();

    for path in paths {
        let relative = path
            .strip_prefix(root)
            .unwrap_or(&path)
            .to_string_lossy()
            .replace('\\', "/");
        // Anchored entries are matched from the repository root; the three
        // bare directory names are matched at ANY depth.
        //
        // The depth part is not defensive tidiness: the moment a second package
        // joined the pnpm workspace, `docs-site/node_modules` appeared, did not
        // match the root-anchored `node_modules`, and the gates began walking
        // the vendored color output through a symlink — reporting hundreds of
        // findings in a file this repository is forbidden to edit.
        if relative
            .split('/')
            .any(|part| matches!(part, ".git" | "target" | "node_modules"))
        {
            continue;
        }
        if SKIP
            .iter()
            .any(|skip| relative == *skip || relative.starts_with(&format!("{skip}/")))
        {
            continue;
        }
        if path.is_dir() {
            walk(root, &path, extensions, into)?;
        } else if path
            .extension()
            .is_some_and(|e| extensions.iter().any(|w| e == *w))
        {
            into.push(path);
        }
    }
    Ok(())
}

/// Applies every gate to one file's text.
fn inspect(
    file: &str,
    text: &str,
    breakpoints: &[String],
    declared: &std::collections::BTreeSet<String>,
    findings: &mut Vec<Finding>,
) {
    // A generated file is verified against the spec, which is stronger than a
    // lint over its text — and it is allowed to contain whatever the spec says.
    if text.contains("Generated by noctua-design — do not edit.") {
        return;
    }

    cited_sources(file, text, findings);

    // Tracked across lines, because a CSS block comment's second line contains
    // no `/*` and a line-by-line strip would read its prose as code. Three of
    // this repository's own findings were numbers inside explanatory comments,
    // and a gate that flags its own documentation is a gate people learn to
    // ignore.
    let mut in_block_comment = false;

    for (index, line) in text.lines().enumerate() {
        let was_in_comment = in_block_comment;
        in_block_comment = block_comment_state(line, in_block_comment);
        if was_in_comment {
            continue;
        }
        if line.contains(ALLOW) {
            continue;
        }
        let number = index + 1;
        let code = strip_strings_and_comments(line);

        // A media prelude is checked by its own gate, which is stricter than
        // the token gate rather than weaker: a length there cannot be a custom
        // property (a media query cannot read one), so the useful question is
        // not "is this a token" but "is this a DECLARED breakpoint".
        //
        // AND `@container` IS THE SAME QUESTION. It was not on this list until
        // a container query was written, at which point the token gate flagged
        // its `30rem` — correctly, since nothing else was looking at it, and
        // uselessly, since a container query cannot read a custom property
        // either. Routing it here is the stricter reading of the two: it now
        // has to be a declared breakpoint, and `@container (max-width: …)` is
        // refused for exactly the reason `@media (max-width: …)` is.
        let prelude = code.trim_start();
        if prelude.starts_with("@media") || prelude.starts_with("@container") {
            if let Some(message) = media_prelude(&code, breakpoints) {
                findings.push(Finding {
                    file: file.to_owned(),
                    line: number,
                    message,
                });
            }
            continue;
        }

        if let Some(message) = color_literal(&code) {
            findings.push(Finding {
                file: file.to_owned(),
                line: number,
                message,
            });
        }
        if let Some(message) = token_literal(&code) {
            findings.push(Finding {
                file: file.to_owned(),
                line: number,
                message,
            });
        }
        // These two read the line with only its COMMENT stripped, not its
        // strings: a font family and a Tailwind class both live inside a
        // string, which is precisely where they are invisible to a check that
        // strips strings first. But prose explaining *why* a family must not be
        // named is not a violation — and this file's own doc comments name
        // every family in the system.
        let uncommented = strip_comments(line);
        if let Some(message) = font_family(&uncommented) {
            findings.push(Finding {
                file: file.to_owned(),
                line: number,
                message,
            });
        }
        if let Some(message) = arbitrary_value(&uncommented) {
            findings.push(Finding {
                file: file.to_owned(),
                line: number,
                message,
            });
        }
        if let Some(message) = frozen_color_indirection(&code) {
            findings.push(Finding {
                file: file.to_owned(),
                line: number,
                message,
            });
        }
        if let Some(message) = color_read_from_dom(&code) {
            findings.push(Finding {
                file: file.to_owned(),
                line: number,
                message,
            });
        }
        if let Some(message) = translated_fragment(&code) {
            findings.push(Finding {
                file: file.to_owned(),
                line: number,
                message,
            });
        }
        if let Some(message) = hand_drawn_icon(&code) {
            findings.push(Finding {
                file: file.to_owned(),
                line: number,
                message,
            });
        }
        if let Some(message) = unknown_token(&code, declared) {
            findings.push(Finding {
                file: file.to_owned(),
                line: number,
                message,
            });
        }
        if let Some(message) = hand_written_glass(&code) {
            findings.push(Finding {
                file: file.to_owned(),
                line: number,
                message,
            });
        }
    }
}

/// There is one glass recipe, and it is emitted.
///
/// # What four copies cost
///
/// The shell wrote `backdrop-filter` four times — a utility, the header's
/// backdrop, the settings panel and the drawer — each repeating the same blur
/// over the same `color-mix`. They drifted: the drawer switched its glass off
/// above `lg`, so on every desktop viewport the sidebar and the settings panel
/// were different materials on the same page.
///
/// And a `backdrop-filter` whose ancestor has one is **inert** — it samples
/// nothing and reports nothing. Both failures are invisible to a compiler and
/// obvious to a reader, which is the worst combination there is.
///
/// The recipe lives in `dist/theme.css` as `.noctua-glass`, emitted from
/// `spec/tokens.toml`. Generated files are exempt by the header check at the
/// top of [`inspect`].
fn hand_written_glass(code: &str) -> Option<String> {
    code.contains("backdrop-filter").then(|| {
        "a second glass recipe. There is one, `.noctua-glass`, emitted from \
         spec/tokens.toml — apply the class instead. Four hand-written copies \
         drifted into two materials on one page, and a nested backdrop-filter is \
         inert with nothing to report"
            .to_owned()
    })
}

/// No `var()` may name a custom property nothing declares.
///
/// # Why this is not caught by anything else
///
/// `var(--noctua-space-40)` is valid CSS. There is no such token, so the whole
/// declaration is invalid at computed-value time and the browser drops it —
/// silently. `grid-template-columns: repeat(auto-fill, minmax(var(--nope), 1fr))`
/// does not error; the grid simply becomes one column, and it looks like a
/// layout decision. That happened here, in the same change that added a gate
/// for a different kind of silent failure.
///
/// `--nc-*` names are exempt: they come from the vendored color output, all
/// 1,767 of them, and are already guarded by `color_literal` and the vendor
/// check.
fn unknown_token(code: &str, declared: &std::collections::BTreeSet<String>) -> Option<String> {
    let mut rest = code;
    while let Some(at) = rest.find("var(--") {
        rest = &rest[at + "var(".len()..];
        let name: String = rest
            .chars()
            .take_while(|c| c.is_ascii_alphanumeric() || *c == '-' || *c == '_')
            .collect();
        rest = &rest[name.len()..];
        // A name ending in `-` is one an interpolation was cut out of:
        // `var(--noctua-space-{name})` in `rsx!` arrives here as
        // `var(--noctua-space-)`. The value is composed at runtime, so there is
        // nothing static to check.
        if name.is_empty() || name.ends_with('-') {
            continue;
        }
        if !declared.contains(&name) {
            return Some(format!(
                "`var({name})` names a custom property nothing declares. The declaration \
                 will be dropped at computed-value time with no error, and the element \
                 will quietly fall back — check the name against dist/tokens.css"
            ));
        }
    }
    None
}

/// Every line naming another design system as a source.
///
/// A PASS OF ITS OWN, BECAUSE IT READS THE RAW LINE. Every other gate here is
/// about code, so every other one reads a line with its comments taken off.
/// This one is about prose: of the twenty-nine places that cited another design
/// system as a source, most were comments, and a check that cannot see a
/// comment cannot see the problem.
fn cited_sources(file: &str, text: &str, findings: &mut Vec<Finding>) {
    for (index, line) in text.lines().enumerate() {
        if line.contains(ALLOW) {
            continue;
        }
        if let Some(message) = borrowed_authority(line) {
            findings.push(Finding {
                file: file.to_owned(),
                line: index + 1,
                message,
            });
        }
    }
}

/// No other design system is named as a source.
///
/// # Why this is a gate and not a preference
///
/// Twenty-nine places in this repository cited GOV.UK — in prop documentation a
/// reader sees, in stylesheet comments, in the master reference, and in the
/// contract files that generate all three. It read as attribution. It was not:
/// the name had been mentioned once, in a prompt, as an example of the kind of
/// thing to aim for. Nothing here was taken from them, so crediting them was a
/// claim about a relationship that does not exist, made on their behalf.
///
/// A measurement, a WCAG number or an accessibility technique is a fact and
/// stays. What may not stay is the name attached to it.
///
/// THIS IS NOT ABOUT VENDORED WORK. `assets/icons/ATTRIBUTION.md`,
/// `assets/vendor/`, `assets/fonts/` and the palette under `packages/tokens`
/// carry real licences for real code and real drawings, and those attributions
/// are obligations. The names below are design systems cited as authority.
fn borrowed_authority(code: &str) -> Option<String> {
    /// Named as a source, in a repository that took nothing from any of them.
    const CITED: [&str; 11] = [
        "GOV.UK",
        "govuk",
        "Material Design",
        "Carbon Design",
        "Ant Design",
        "Fluent UI",
        "Lightning Design",
        "Polaris",
        "USWDS",
        "Chakra",
        "Radix UI",
    ];

    let named = CITED.iter().find(|name| code.contains(*name))?;
    Some(format!(
        "`{named}` is named as a source, and nothing here was taken from it"
    ))
}

/// No icon is drawn outside the generated module.
///
/// # The bug this exists for
///
/// The shell hand-wrote its own `Icon`: a `match` over `&str` with three arms
/// and a `_ => ""` fallback. A call for an icon it did not have compiled
/// cleanly and rendered `<path d="">` — a 44×44 clickable void in the header of
/// every page, which is what shipped.
///
/// Drawing an icon here is what makes that possible. Declared in
/// `spec/icons.toml` instead, the name is a generated enum in Rust and a union
/// in TypeScript, so the same call does not compile in either language. The
/// generated module is exempt by the header check at the top of [`inspect`].
fn hand_drawn_icon(code: &str) -> Option<String> {
    // `svg {` is the `rsx!` form; `<svg` and `createElement("svg"` are the
    // others. A `.nd-icon-glyph` selector in CSS is styling, not drawing.
    let drawn = code.contains("<svg")
        || code.contains("<path")
        || code.contains("createElement(\"svg\"")
        || (code.contains("svg {") && !code.contains('.'));
    drawn.then(|| {
        "an icon drawn by hand. Declare it in spec/icons.toml and render it with `Icon`: \
         a name that is a string rather than the generated enum is what shipped a \
         header link with an empty path and no visible icon"
            .to_owned()
    })
}

/// A custom property must not bake a color token into its value.
///
/// # The single most expensive mistake this system can make
///
/// A `var()` resolves **where it is declared**, not where it is read. So
///
/// ```css
/// :root { --nd-edge: 1px solid var(--nc-color-border); }
/// ```
///
/// freezes to the *root's* palette. Every element that later reads `--nd-edge`
/// — including one inside a `ThemeScope` on a different palette in a different
/// mode — draws the page's border color. Nothing errors. Every token still
/// resolves to something. It simply looks slightly wrong in a way nobody can
/// name, and it survives review because the declaration reads perfectly.
///
/// This gate found exactly that bug in this repository's own shell stylesheet,
/// which had been reviewed twice by the person who wrote the rule.
///
/// **The fix is always the same**: move the `var(--nc-…)` to the point of use,
/// where the palette is already correct. Keep the dimensionless part in the
/// custom property if it is worth naming.
///
/// `dist/scope.css` is the one legitimate exception, and it is generated — so it
/// never reaches this gate.
fn frozen_color_indirection(code: &str) -> Option<String> {
    let trimmed = code.trim_start();
    if !trimmed.starts_with("--") {
        return None;
    }
    let (name, value) = trimmed.split_once(':')?;
    if !value.contains("var(--nc-") {
        return None;
    }
    Some(format!(
        "`{}` bakes a color token into a custom property. A var() resolves where it \
         is DECLARED, so this freezes to the palette of whatever element carries it — \
         a themed component reading it would paint the page's colors. Move the \
         var(--nc-…) to the point of use",
        name.trim()
    ))
}

/// Never read a color back out of the DOM.
///
/// `getComputedStyle(el).color` returns whatever the engine felt like
/// serialising, in whatever color space it chose, with whatever precision. Two
/// of those strings comparing equal proves nothing about the pixels, and two
/// comparing unequal proves nothing either — which makes a test written this way
/// pass on a color it never actually checked.
///
/// Paint into a 1×1 canvas and read the pixel:
///
/// ```js
/// const c = document.createElement("canvas");
/// c.width = c.height = 1;
/// const ctx = c.getContext("2d");
/// ctx.fillStyle = whateverTheElementResolvedTo;
/// ctx.fillRect(0, 0, 1, 1);
/// const [r, g, b] = ctx.getImageData(0, 0, 1, 1).data;
/// ```
///
/// Reading a *length* that way is fine, and this gate does not touch it.
fn color_read_from_dom(code: &str) -> Option<String> {
    if !code.contains("getComputedStyle") {
        return None;
    }
    for property in [
        ".color",
        ".backgroundColor",
        ".borderColor",
        ".fill",
        ".stroke",
    ] {
        if code.contains(property) {
            return Some(format!(
                "`getComputedStyle(…){property}` reads a color out of the DOM. The engine \
                 serialises in whatever space and precision it likes, so comparing two of \
                 those strings proves nothing about the pixels. Paint into a 1×1 canvas \
                 and read getImageData instead"
            ));
        }
    }
    None
}

/// A sentence is one message, never two joined at run time.
///
/// `NOCTUA.md §9.9` rule 1. Word order, grammatical gender and agreement all
/// differ between languages: `t(Key::Delete) + " " + t(Key::Item)` reads
/// correctly in English and is ungrammatical in Portuguese, and no translator
/// can fix it because neither half is a sentence they can move.
///
/// A whole sentence with a `{placeholder}` hole in it survives translation.
/// Two halves do not. `noctua_design_i18n::fill` is the sanctioned way.
fn translated_fragment(code: &str) -> Option<String> {
    // A lookup joined to anything with `+`, in either language's spelling.
    for lookup in [".message(", "t(Key::", "t(locale,"] {
        let Some(at) = code.find(lookup) else {
            continue;
        };
        let after = &code[at..];
        // Find the end of the call, then see whether it is being concatenated.
        let mut depth = 0i32;
        for (index, ch) in after.char_indices() {
            match ch {
                '(' => depth += 1,
                ')' => {
                    depth -= 1;
                    if depth == 0 {
                        let tail = after[index + 1..].trim_start();
                        if tail.starts_with('+') {
                            return Some(
                                "a translated message is being concatenated. Word order, \
                                 gender and agreement differ between languages, so a \
                                 sentence assembled from fragments cannot be translated. \
                                 Make it one message with a {placeholder} and use `fill`"
                                    .to_owned(),
                            );
                        }
                        break;
                    }
                }
                _ => {}
            }
        }
    }
    None
}

/// Whether the line leaves us inside a `/* … */` block.
fn block_comment_state(line: &str, was_inside: bool) -> bool {
    let mut inside = was_inside;
    let chars: Vec<char> = line.chars().collect();
    let mut index = 0;
    // Tracked because a `/*` inside either is not a comment opener, and this
    // gate has no parser: `strip_strings_and_comments` runs per line and
    // cannot answer a question about state that crosses lines.
    let mut in_string = false;
    let mut escaped = false;

    while index + 1 < chars.len() {
        let (here, next) = (chars[index], chars[index + 1]);

        if inside {
            if here == '*' && next == '/' {
                inside = false;
                index += 2;
            } else {
                index += 1;
            }
            continue;
        }

        if in_string {
            if escaped {
                escaped = false;
            } else if here == '\\' {
                escaped = true;
            } else if here == '"' {
                in_string = false;
            }
            index += 1;
            continue;
        }

        match (here, next) {
            // A LINE COMMENT ENDS THE LINE, AND A `/*` INSIDE ONE OPENS
            // NOTHING.
            //
            // This is not a nicety. One `//` comment in this repository said
            // `spec/components/*.toml`, and that `/*` put every gate into a
            // block comment that never closed — so **every gate stopped
            // checking the rest of the file**, silently, for a whole stage. It
            // was found only because deleting the comment made two real
            // findings appear out of nowhere.
            ('/', '/') => return false,
            ('/', '*') => {
                inside = true;
                index += 2;
            }
            ('"', _) => {
                in_string = true;
                index += 1;
            }
            _ => index += 1,
        }
    }
    inside
}

/// Every breakpoint is a **declared minimum width**.
///
/// The prelude of a `@media` **or `@container`** rule.
///
/// Two rules, and the second is the one that has no other enforcement:
///
/// * `max-width` is rejected outright. This system is mobile-first — the base
///   styles are the narrow ones — and a `max-width` query is how a layout grows
///   a dead zone at `calc(64rem - 1px)` that nobody ever tests at.
/// * A `min-width` must equal a breakpoint declared in `spec/tokens.toml`. A
///   media query cannot read a custom property, so the token gate can never
///   apply here; without this, an undeclared breakpoint is caught by nothing at
///   all, which is what made the old blanket exemption a hole rather than a
///   rule.
///
/// A container query answers to both. It asks a different question — how wide
/// is the box rather than how wide is the window — but the same two answers are
/// wrong for the same two reasons, and the system has one scale of widths, not
/// one per at-rule.
fn media_prelude(code: &str, breakpoints: &[String]) -> Option<String> {
    if code.contains("max-width") {
        return Some(
            "`max-width` in a media query. This system is mobile-first: the base styles \
             are the narrow ones and every breakpoint is a minimum. Invert the rule — \
             declare the narrow case unconditionally and override it from `min-width` up"
                .to_owned(),
        );
    }

    let mut rest = code;
    while let Some(at) = rest.find("min-width:") {
        rest = &rest[at + "min-width:".len()..];
        let value: String = rest
            .trim_start()
            .chars()
            .take_while(|c| !c.is_whitespace() && *c != ')')
            .collect();
        if !breakpoints.contains(&value) {
            return Some(format!(
                "`{value}` is not a declared breakpoint. The scale lives in \
                 spec/tokens.toml under [breakpoint] — {} — and a query at any other \
                 width is a layout nothing else in the system agrees with",
                breakpoints.join(", ")
            ));
        }
    }
    None
}

/// Removes a line comment, keeping the string literals before it.
///
/// Different from [`strip_strings_and_comments`], which also blanks strings:
/// the font and Tailwind gates have to see inside strings, because that is
/// where a hardcoded family or class lives.
fn strip_comments(line: &str) -> String {
    for marker in ["//!", "///", "//", "/*", "*", "#"] {
        let trimmed = line.trim_start();
        if trimmed.starts_with(marker) {
            return String::new();
        }
    }
    line.split_once("//")
        .map_or(line, |(code, _)| code)
        .to_owned()
}

/// Blanks out comment text so a gate does not fire on prose.
///
/// A comment explaining *why* a color must not be hardcoded should not be
/// flagged for containing `#ff0000`.
fn strip_strings_and_comments(line: &str) -> String {
    let without_comment = line
        .split_once("//")
        .map_or(line, |(code, _)| code)
        .split_once("/*")
        .map_or_else(
            || line.split_once("//").map_or(line, |(code, _)| code),
            |(code, _)| code,
        );
    without_comment.to_owned()
}

/// No color may be defined in this repository.
///
/// Colors come from `noctua-colors` as `--nc-*` tokens. A literal here is a
/// color that will not follow a palette change and that no contrast gate ever
/// measured. `NOCTUA.md §8.8`.
fn color_literal(code: &str) -> Option<String> {
    // A hex color: # followed by exactly 3, 4, 6 or 8 hex digits, not part of
    // a longer word.
    let bytes: Vec<char> = code.chars().collect();
    for (index, ch) in bytes.iter().enumerate() {
        if *ch != '#' {
            continue;
        }
        let digits = bytes[index + 1..]
            .iter()
            .take_while(|c| c.is_ascii_hexdigit())
            .count();
        let ends_cleanly = bytes
            .get(index + 1 + digits)
            .is_none_or(|c| !c.is_alphanumeric() && *c != '_' && *c != '-');
        if matches!(digits, 3 | 4 | 6 | 8) && ends_cleanly {
            return Some(
                "a hex color. Colors come from noctua-colors as --nc-* tokens; a literal \
                 here will not follow a palette change and no contrast gate has measured it"
                    .to_owned(),
            );
        }
    }

    // A CALL, NOT A RUN OF LETTERS THAT ENDS THAT WAY.
    //
    // `rgbToOklch(color)` contains `lch(` and is a function name; so does
    // `oklch(0.54 0.24 292)`, and only the second defines a colour. The
    // difference is what comes BEFORE: a call's name starts at a boundary,
    // and a name that merely ends in `lch` has an identifier character in
    // front of it. Without this the gate refused the one file in this
    // repository that is allowed to know what OKLCH is — and refusing the
    // right answer is how a gate teaches people to reach for the escape hatch.
    let bytes: Vec<char> = code.chars().collect();
    for function in [
        "rgb(", "rgba(", "hsl(", "hsla(", "oklch(", "oklab(", "lab(", "lch(",
    ] {
        let mut from = 0;
        while let Some(at) = code[from..].find(function) {
            let start = code[..from + at].chars().count();
            let clean = start == 0
                || bytes
                    .get(start - 1)
                    .is_none_or(|c| !c.is_alphanumeric() && *c != '_' && *c != '-');
            if clean {
                return Some(format!(
                    "`{function}` defines a color. Colors come from noctua-colors as --nc-* tokens"
                ));
            }
            from += at + function.len();
        }
    }
    None
}

/// No raw length or duration in component source.
///
/// Spacing, radii, sizes and durations come from the token layer, so a change
/// to the scale reaches every component. A raw `13px` is a value that will sit
/// between two steps forever and that nobody will find when the scale moves.
fn token_literal(code: &str) -> Option<String> {
    let chars: Vec<char> = code.chars().collect();
    for (index, _) in chars.iter().enumerate() {
        // Find a number, then look at what follows it.
        if index > 0 && (chars[index - 1].is_ascii_digit() || chars[index - 1] == '.') {
            continue;
        }
        let digits = chars[index..]
            .iter()
            .take_while(|c| c.is_ascii_digit() || **c == '.')
            .count();
        if digits == 0 {
            continue;
        }
        let rest: String = chars[index + digits..].iter().take(3).collect();

        for unit in ["px", "rem", "em", "ms"] {
            if rest.starts_with(unit) {
                let after = chars.get(index + digits + unit.len());
                if after.is_none_or(|c| !c.is_alphanumeric()) {
                    // `0` is dimensionless in CSS and needs no token.
                    let value: String = chars[index..index + digits].iter().collect();
                    if value.parse::<f64>() == Ok(0.0) {
                        continue;
                    }
                    return Some(format!(
                        "`{value}{unit}` is a raw value. Spacing, radii, sizes and durations \
                         come from the token layer so a change to the scale reaches every \
                         component"
                    ));
                }
            }
        }
    }
    None
}

/// No component names a font family directly.
///
/// A component that hardcodes `"Noto Sans"` cannot honour the interface-font
/// setting and will not fall back correctly. `NOCTUA.md §7.4`.
fn font_family(line: &str) -> Option<String> {
    const FAMILIES: [&str; 5] = [
        "Noto Sans",
        "Noto Serif",
        "Noto Sans Display",
        "Noctua Iosevka",
        "Symbols Nerd Font",
    ];

    // The property itself is only a finding when its VALUE does not name a
    // token. Matching the property name flagged `font-family:
    // var(--noctua-font-sans)` — the correct spelling — which is how a gate
    // teaches people that the right answer is also an error.
    if let Some((_, value)) = line.split_once("font-family:") {
        if !value.contains("var(--noctua-font-") {
            return Some(
                "`font-family:` does not name a font token. Use var(--noctua-font-*), or \
                 the interface-font setting cannot reach this and the fallback chain is \
                 lost"
                    .to_owned(),
            );
        }
    }

    for family in FAMILIES {
        if line.contains(family) {
            return Some(format!(
                "`{family}` names a font directly. Use var(--noctua-font-*), or the \
                 interface-font setting cannot reach this and the fallback chain is lost"
            ));
        }
    }
    None
}

/// No Tailwind arbitrary value.
///
/// `p-[13px]` is a token literal wearing a different hat: it bypasses the scale
/// exactly as a raw `13px` does, and it is harder to find.
fn arbitrary_value(line: &str) -> Option<String> {
    let bytes: Vec<char> = line.chars().collect();
    for (index, ch) in bytes.iter().enumerate() {
        if *ch != '[' || index == 0 {
            continue;
        }
        // A Tailwind arbitrary value is `<utility>-[value]` — a hyphen
        // immediately before the bracket, and no space inside it.
        if bytes[index - 1] != '-' {
            continue;
        }
        let inside: String = bytes[index + 1..]
            .iter()
            .take_while(|c| **c != ']')
            .collect();
        if !inside.is_empty()
            && !inside.contains(' ')
            && bytes[index + 1 + inside.len()..].first() == Some(&']')
        {
            return Some(format!(
                "`-[{inside}]` is a Tailwind arbitrary value, which bypasses the token \
                 scale exactly as a raw literal does and is harder to find"
            ));
        }
    }
    None
}

